"""Шаблоны промптов (файлы *.md) и утилиты безопасной подстановки данных."""

import re


def escape_closing_tag(text: str, tag: str) -> str:
    """Данные не могут «закрыть» свой блок: `</tag>` внутри текста экранируется.

    Без учёта регистра и пробелов внутри тега — иначе `</DOCUMENT >` прошёл бы мимо.
    """
    return re.sub(rf"</\s*{tag}\s*>", f"<\\/{tag}>", text, flags=re.IGNORECASE)
